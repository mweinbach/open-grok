    #[test]
    fn shared_redaction_removes_complete_and_unterminated_private_keys() {
        let complete = concat!(
            "prefix -----BEGIN RSA PRIVATE KEY-----\n",
            "hidden-private-material\n",
            "-----END RSA PRIVATE KEY----- suffix"
        );
        let unterminated = "-----BEGIN OPENSSH PRIVATE KEY-----\nhidden-unterminated";

        assert!(!redact_sensitive_text(complete).contains("hidden-private-material"));
        assert!(!redact_sensitive_text(unterminated).contains("hidden-unterminated"));
        assert!(redact_sensitive_text(complete).contains("suffix"));
    }

