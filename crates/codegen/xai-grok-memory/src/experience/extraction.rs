const MAX_STORED_TEXT_CHARS: usize = 240;
const MAX_COMMAND_CHARS: usize = 180;
const MAX_REDACTED_TEXT_CHARS: usize = 8_192;
const MAX_KEY_DECISIONS: usize = 8;
const MAX_OBSERVED_EVENTS: usize = 128;
const MAX_FAILURE_LESSONS: usize = 4;
const MAX_VERIFICATION_LESSONS: usize = 3;

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(default)]
pub struct ObservedEvent {
    pub tool_name: String,
    pub command: Option<String>,
    pub output: String,
    pub exit_code: Option<i32>,
    pub succeeded: Option<bool>,
    pub timestamp: i64,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(default)]
pub struct RunObservation {
    pub run_id: String,
    pub task_type: String,
    pub task_summary: String,
    pub repository_id: String,
    pub repository_revision: Option<String>,
    pub environment: String,
    pub strategy: String,
    pub strategy_rationale: String,
    pub key_decisions: Vec<String>,
    pub changed_paths: Vec<String>,
    pub events: Vec<ObservedEvent>,
    pub judge_feedback: Option<String>,
    pub user_feedback: Option<String>,
    pub completed: Option<bool>,
}

pub fn classify_failure(text: &str) -> Option<FailureClass> {
    let text = text.to_ascii_lowercase();

    if contains_any(
        &text,
        &[
            "database is locked",
            "database locked",
            "deadlock detected",
            "lock wait timeout",
            "could not obtain lock",
            "lock contention",
            "sqlite_busy",
        ],
    ) {
        return Some(FailureClass::DatabaseLock);
    }

    if contains_any(
        &text,
        &[
            "generated file",
            "generated code",
            "generated source",
            "automatically generated",
            "auto-generated",
            "autogenerated",
            "do not edit",
            "overwritten during build",
        ],
    ) {
        return Some(FailureClass::GeneratedFile);
    }

    if contains_any(
        &text,
        &[
            "regression detected",
            "regression failure",
            "introduced a regression",
            "regression test failed",
            "performance regression",
        ],
    ) {
        return Some(FailureClass::Regression);
    }

    if contains_any(
        &text,
        &[
            "permission denied",
            "operation not permitted",
            "access denied",
            "forbidden",
            "eacces",
            "unauthorized",
        ],
    ) {
        return Some(FailureClass::Permission);
    }

    if contains_any(
        &text,
        &[
            "timed out",
            "timeout exceeded",
            "deadline exceeded",
            "operation timeout",
            "request timeout",
        ],
    ) {
        return Some(FailureClass::Timeout);
    }

    if contains_any(
        &text,
        &[
            "dependency resolution",
            "failed to select a version",
            "could not resolve dependency",
            "unable to resolve dependency",
            "module not found",
            "cannot find module",
            "no matching package",
            "package not found",
            "unresolved import",
        ],
    ) {
        return Some(FailureClass::Dependency);
    }

    if contains_any(
        &text,
        &[
            "type mismatch",
            "type error",
            "typecheck failed",
            "type check failed",
            "incompatible types",
            "is not assignable to type",
            "error ts",
            "mypy:",
        ],
    ) {
        return Some(FailureClass::TypeCheck);
    }

    if contains_any(
        &text,
        &[
            "lint failed",
            "lint error",
            "linting failed",
            "clippy::",
            "eslint error",
            "ruff failed",
        ],
    ) {
        return Some(FailureClass::Lint);
    }

    if contains_any(
        &text,
        &[
            "test failed",
            "tests failed",
            "failing test",
            "failed test",
            "test result: failed",
            "failures:",
            "assertion failed",
            "assertionerror",
            "assertionerror:",
            "panicked at",
        ],
    ) {
        return Some(FailureClass::Test);
    }

    if contains_any(
        &text,
        &[
            "build failed",
            "compilation failed",
            "compile error",
            "compiler error",
            "could not compile",
            "error[e",
            "build error",
        ],
    ) {
        return Some(FailureClass::Build);
    }

    None
}

pub fn classify_tool_evidence(event: &ObservedEvent) -> Option<EvidenceSignal> {
    let tool_name = event.tool_name.to_ascii_lowercase();

    if !matches!(
        tool_name.as_str(),
        "run_terminal_command"
            | "run_terminal_cmd"
            | "exec_command"
            | "run_command"
            | "bash"
            | "shell"
            | "judge"
            | "evaluator"
            | "external_judge"
            | "external_evaluator"
    ) {
        return None;
    }

    let verdict = event_verdict(event)?;
    let kind = classify_evidence_kind(event);
    let command = event
        .command
        .as_deref()
        .map(|command| sanitize_text(command, MAX_COMMAND_CHARS))
        .filter(|command| !command.is_empty());
    let summary = summarize_output(event, verdict);
    let score = if kind == EvidenceKind::Test {
        test_result_score(&event.output).or(match verdict {
            EvidenceVerdict::Passed => Some(1.0),
            EvidenceVerdict::Failed => Some(0.0),
            EvidenceVerdict::Neutral => None,
        })
    } else {
        match verdict {
            EvidenceVerdict::Passed => Some(1.0),
            EvidenceVerdict::Failed => Some(0.0),
            EvidenceVerdict::Neutral => None,
        }
    };

    Some(EvidenceSignal {
        kind,
        verdict,
        command,
        summary,
        score,
        observed_at: event.timestamp,
        source_run_id: None,
    })
}

pub fn extract_experiences(observation: &RunObservation) -> Vec<ExperienceMemory> {
    let source_run_id = sanitize_text(&observation.run_id, MAX_COMMAND_CHARS);
    let mut evidence: Vec<EvidenceSignal> = observation
        .events
        .iter()
        .skip(observation.events.len().saturating_sub(MAX_OBSERVED_EVENTS))
        .filter_map(classify_tool_evidence)
        .map(|mut signal| {
            signal.source_run_id = (!source_run_id.is_empty()).then(|| source_run_id.clone());
            signal
        })
        .collect();

    if !evidence.iter().any(EvidenceSignal::is_objective) {
        return Vec::new();
    }

    evidence.sort_by_key(|signal| signal.observed_at);
    let now = evidence
        .iter()
        .map(|signal| signal.observed_at)
        .max()
        .unwrap_or_default();
    let scope = observation_scope(&observation.changed_paths);
    let mut memories = Vec::new();
    let mut seen_failures = HashSet::new();

    for signal in evidence
        .iter()
        .filter(|signal| signal.verdict == EvidenceVerdict::Failed)
    {
        let failure_class = failure_class_for_signal(signal);

        if !seen_failures.insert(failure_class) {
            continue;
        }

        memories.push(build_failure_memory(
            observation,
            signal,
            failure_class,
            scope,
            now,
        ));

        if failure_class == FailureClass::GeneratedFile && proves_generated_file_behavior(signal) {
            memories.push(build_environmental_fact(observation, signal, now));
        }

        if seen_failures.len() >= MAX_FAILURE_LESSONS {
            break;
        }
    }

    let mut seen_verifications = HashSet::new();

    for signal in evidence
        .iter()
        .filter(|signal| signal.verdict == EvidenceVerdict::Passed && signal.is_verification())
    {
        let verification_key = format!(
            "{:?}:{}",
            signal.kind,
            signal.command.as_deref().unwrap_or_default()
        );

        if !seen_verifications.insert(verification_key) {
            continue;
        }

        memories.push(build_verification_memory(observation, signal, now));

        if seen_verifications.len() >= MAX_VERIFICATION_LESSONS {
            break;
        }
    }

    if let Some(signal) = evidence.iter().find(|signal| {
        signal.is_objective()
            && signal.verdict == EvidenceVerdict::Passed
            && proves_architectural_boundary(signal)
    }) {
        memories.push(build_architectural_lesson(observation, signal, now));
    }

    if let Some(conflicting_signals) = unresolved_objective_contradiction(&evidence) {
        memories.push(build_uncertain_hypothesis(
            observation,
            &conflicting_signals,
            now,
        ));
    }

    if should_extract_successful_pattern(observation, &evidence) {
        memories.push(build_successful_pattern(observation, &evidence, scope, now));
    }

    memories
}

fn event_verdict(event: &ObservedEvent) -> Option<EvidenceVerdict> {
    if event.exit_code.is_some_and(|exit_code| exit_code != 0) || event.succeeded == Some(false) {
        return Some(EvidenceVerdict::Failed);
    }

    if event.exit_code == Some(0) || event.succeeded == Some(true) {
        return Some(EvidenceVerdict::Passed);
    }

    None
}

fn classify_evidence_kind(event: &ObservedEvent) -> EvidenceKind {
    let command = event
        .command
        .as_deref()
        .unwrap_or_default()
        .to_ascii_lowercase();
    let tool_name = event.tool_name.to_ascii_lowercase();
    let output = event.output.to_ascii_lowercase();
    let command_and_tool = format!("{command} {tool_name}");

    if matches!(
        tool_name.as_str(),
        "judge" | "evaluator" | "external_judge" | "external_evaluator"
    ) {
        return EvidenceKind::Judge;
    }

    if contains_any(
        &command_and_tool,
        &[
            "regression",
            "cargo test",
            " test ",
            "benchmark",
            "cargo bench",
        ],
    ) && contains_any(
        &output,
        &[
            "regression detected",
            "performance regression",
            "introduced a regression",
        ],
    ) {
        return EvidenceKind::Regression;
    }

    if contains_any(
        &command_and_tool,
        &["benchmark", "cargo bench", "hyperfine"],
    ) {
        return EvidenceKind::Benchmark;
    }

    if contains_any(
        &command_and_tool,
        &[
            "clippy",
            "eslint",
            "ruff",
            "flake8",
            "golangci-lint",
            " lint",
        ],
    ) {
        return EvidenceKind::Lint;
    }

    if contains_any(
        &command_and_tool,
        &[
            "typecheck",
            "type-check",
            "mypy",
            "pyright",
            "tsc ",
            "tsc --",
        ],
    ) {
        return EvidenceKind::TypeCheck;
    }

    if contains_any(
        &command_and_tool,
        &[
            "cargo test",
            "cargo nextest",
            "pytest",
            "jest",
            "vitest",
            "go test",
            "npm test",
            "npm run test",
            "pnpm test",
            "yarn test",
            "gradle test",
            "mvn test",
            " test ",
            "test_runner",
        ],
    ) {
        return EvidenceKind::Test;
    }

    if contains_any(
        &command_and_tool,
        &[
            "cargo build",
            "cargo check",
            "rustc",
            "gradle assemble",
            "npm run build",
            "pnpm build",
            " compile",
            "make ",
        ],
    ) {
        return EvidenceKind::Compile;
    }

    if contains_any(&command_and_tool, &["git diff", "diff --check"]) {
        return EvidenceKind::Diff;
    }

    if contains_any(&command_and_tool, &["runtime", "integration_run"]) {
        return EvidenceKind::Runtime;
    }

    EvidenceKind::CommandExit
}

fn summarize_output(event: &ObservedEvent, verdict: EvidenceVerdict) -> String {
    let preferred_line = event
        .output
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty())
        .find(|line| {
            let line = line.to_ascii_lowercase();
            classify_failure(&line).is_some()
                || contains_any(
                    &line,
                    &[
                        "test result:",
                        "error:",
                        "failed",
                        "passed",
                        "build successful",
                        "exit code:",
                    ],
                )
        })
        .or_else(|| {
            event
                .output
                .lines()
                .map(str::trim)
                .find(|line| !line.is_empty())
        });

    if let Some(line) = preferred_line {
        return sanitize_text(line, MAX_STORED_TEXT_CHARS);
    }

    match (event.exit_code, verdict) {
        (Some(exit_code), _) => format!("Command exited with status {exit_code}"),
        (_, EvidenceVerdict::Passed) => "Tool reported successful completion".to_string(),
        (_, EvidenceVerdict::Failed) => "Tool reported unsuccessful completion".to_string(),
        (_, EvidenceVerdict::Neutral) => "Tool produced inconclusive evidence".to_string(),
    }
}

fn test_result_score(output: &str) -> Option<f64> {
    let mut previous_number = None;
    let mut passed = None;
    let mut failed = None;

    for token in output.split(|character: char| !character.is_ascii_alphanumeric()) {
        if token.is_empty() {
            continue;
        }

        if let Ok(number) = token.parse::<u64>() {
            previous_number = Some(number);
            continue;
        }

        match token.to_ascii_lowercase().as_str() {
            "passed" | "passing" => passed = previous_number,
            "failed" | "failing" => failed = previous_number,
            _ => {}
        }

        previous_number = None;
    }

    match (passed, failed) {
        (Some(passed), Some(failed)) if passed.saturating_add(failed) > 0 => {
            Some(passed as f64 / passed.saturating_add(failed) as f64)
        }
        _ => None,
    }
}

fn observation_scope(changed_paths: &[String]) -> ExperienceScope {
    let concrete_paths: Vec<&str> = changed_paths
        .iter()
        .map(String::as_str)
        .filter(|path| is_concrete_path(path))
        .collect();

    match concrete_paths.as_slice() {
        [] => ExperienceScope::Repository,
        [_] => ExperienceScope::ExactFile,
        [first, remaining @ ..] => {
            let first_parent = first.rsplit_once('/').map(|(parent, _)| parent);

            if first_parent.is_some()
                && remaining
                    .iter()
                    .all(|path| path.rsplit_once('/').map(|(parent, _)| parent) == first_parent)
            {
                ExperienceScope::Module
            } else {
                ExperienceScope::Repository
            }
        }
    }
}

fn is_concrete_path(path: &str) -> bool {
    let path = path.trim();

    !path.is_empty()
        && path != "."
        && path != ".."
        && !path.contains(['\n', '\r', '*', '?'])
        && std::path::Path::new(path)
            .file_name()
            .is_some_and(|name| !name.is_empty())
}

fn failure_class_for_signal(signal: &EvidenceSignal) -> FailureClass {
    let combined = format!(
        "{} {}",
        signal.command.as_deref().unwrap_or_default(),
        signal.summary
    );

    classify_failure(&combined).unwrap_or(match signal.kind {
        EvidenceKind::Test => FailureClass::Test,
        EvidenceKind::Compile => FailureClass::Build,
        EvidenceKind::Lint => FailureClass::Lint,
        EvidenceKind::TypeCheck => FailureClass::TypeCheck,
        EvidenceKind::Regression => FailureClass::Regression,
        _ => FailureClass::Unknown,
    })
}

fn build_failure_memory(
    observation: &RunObservation,
    signal: &EvidenceSignal,
    failure_class: FailureClass,
    scope: ExperienceScope,
    now: i64,
) -> ExperienceMemory {
    let lesson = failure_lesson(failure_class, signal);
    let mut memory = ExperienceMemory::new(
        ExperienceCategory::FailureAntiPattern,
        lesson.clone(),
        sanitize_text(&observation.run_id, MAX_COMMAND_CHARS),
        now,
    );
    let failure_scope = match failure_class {
        FailureClass::Build
        | FailureClass::Test
        | FailureClass::TypeCheck
        | FailureClass::Regression => scope,
        FailureClass::DatabaseLock
        | FailureClass::Lint
        | FailureClass::GeneratedFile
        | FailureClass::Permission
        | FailureClass::Timeout
        | FailureClass::Dependency
        | FailureClass::Unknown => ExperienceScope::Repository,
    };
    populate_common_fields(&mut memory, observation, failure_scope);
    memory.success = Some(false);
    memory.failure_reason = Some(signal.summary.clone());
    memory.what_failed = vec![signal.summary.clone()];
    memory.anti_pattern = Some(lesson.clone());
    memory.recommendation = Some(failure_recommendation(failure_class).to_string());
    memory.evidence = vec![signal.clone()];

    if signal.kind == EvidenceKind::Test {
        memory.tests_run = signal.command.iter().cloned().collect();
        memory.test_results = vec![signal.clone()];
        memory.outcome.functional_correctness = signal.score;
    }

    if matches!(
        failure_class,
        FailureClass::Build | FailureClass::TypeCheck | FailureClass::Regression
    ) {
        memory.outcome.functional_correctness = Some(0.0);
    }

    if failure_class == FailureClass::Regression {
        memory.outcome.regression_risk = Some(0.9);
    }

    memory.refresh_confidence();
    memory
}

fn failure_lesson(failure_class: FailureClass, signal: &EvidenceSignal) -> String {
    match failure_class {
        FailureClass::DatabaseLock => {
            "Avoid parallel database or migration operations when database lock contention is observed".to_string()
        }
        FailureClass::GeneratedFile => {
            "Avoid directly editing generated files; modify the generator or source inputs instead".to_string()
        }
        FailureClass::Permission => {
            "Avoid repeating an operation denied by the current permissions without changing its execution context".to_string()
        }
        FailureClass::Timeout => {
            "Avoid repeating an operation that exceeded its deadline without reducing or restructuring its workload".to_string()
        }
        FailureClass::Dependency => {
            "Resolve the observed dependency or module mismatch before repeating the same implementation strategy".to_string()
        }
        FailureClass::Regression => {
            "Avoid the change pattern associated with the observed regression until its compatibility boundary is understood".to_string()
        }
        _ => {
            let command = signal.command.as_deref().unwrap_or("the same operation");
            sanitize_text(
                &format!(
                    "Avoid repeating `{command}` unchanged after the observed failure: {}",
                    signal.summary
                ),
                MAX_STORED_TEXT_CHARS,
            )
        }
    }
}

fn failure_recommendation(failure_class: FailureClass) -> &'static str {
    match failure_class {
        FailureClass::DatabaseLock => "Serialize database changes or release the conflicting lock",
        FailureClass::Build => "Address the compiler diagnostics before rerunning the build",
        FailureClass::Test => {
            "Use the failing test as a focused reproduction before revising the implementation"
        }
        FailureClass::Lint => "Correct the reported lint violation before repeating validation",
        FailureClass::TypeCheck => "Resolve the reported type mismatch before repeating validation",
        FailureClass::GeneratedFile => {
            "Locate and update the generator, schema, or source template"
        }
        FailureClass::Permission => "Use an authorized operation or change the execution context",
        FailureClass::Timeout => {
            "Reduce the workload, serialize contention, or use a focused check"
        }
        FailureClass::Dependency => "Verify the dependency graph and available module versions",
        FailureClass::Regression => {
            "Reproduce the regression and preserve the existing compatibility boundary"
        }
        FailureClass::Unknown => {
            "Classify the observed failure before selecting a different strategy"
        }
    }
}

fn build_verification_memory(
    observation: &RunObservation,
    signal: &EvidenceSignal,
    now: i64,
) -> ExperienceMemory {
    let command = signal
        .command
        .as_deref()
        .unwrap_or("the focused verification");
    let lesson = sanitize_text(
        &format!(
            "Use `{command}` as an evidence-backed {} check",
            verification_label(signal.kind)
        ),
        MAX_STORED_TEXT_CHARS,
    );
    let mut memory = ExperienceMemory::new(
        ExperienceCategory::ToolProcessLesson,
        lesson.clone(),
        sanitize_text(&observation.run_id, MAX_COMMAND_CHARS),
        now,
    );
    populate_common_fields(&mut memory, observation, ExperienceScope::Repository);
    memory.success = Some(true);
    memory.recommendation = Some(lesson);
    memory.what_worked = vec![signal.summary.clone()];
    memory.evidence = vec![signal.clone()];

    if signal.kind == EvidenceKind::Test {
        memory.tests_run = signal.command.iter().cloned().collect();
        memory.test_results = vec![signal.clone()];
        memory.outcome.functional_correctness = signal.score;
    }

    memory.refresh_confidence();
    memory
}

fn proves_generated_file_behavior(signal: &EvidenceSignal) -> bool {
    let summary = signal.summary.to_ascii_lowercase();
    let identifies_generated_file = contains_any(
        &summary,
        &[
            "generated file",
            "generated code",
            "generated source",
            "automatically generated",
            "auto-generated",
            "autogenerated",
        ],
    );
    let establishes_generated_behavior = contains_any(
        &summary,
        &[
            "overwritten",
            "overwrote",
            "regenerated",
            "regenerate",
            "do not edit",
            "automatically generated",
            "auto-generated",
        ],
    );

    signal.is_objective()
        && signal.verdict == EvidenceVerdict::Failed
        && identifies_generated_file
        && establishes_generated_behavior
}

fn build_environmental_fact(
    observation: &RunObservation,
    signal: &EvidenceSignal,
    now: i64,
) -> ExperienceMemory {
    let summary = signal.summary.to_ascii_lowercase();
    let lesson = if contains_any(&summary, &["overwritten", "overwrote", "regenerated"]) {
        "Generated files in this repository can be overwritten or regenerated; update their generator inputs"
    } else {
        "This repository contains generated files that must be changed through their generator inputs"
    };
    let mut memory = ExperienceMemory::new(
        ExperienceCategory::EnvironmentalFact,
        lesson,
        sanitize_text(&observation.run_id, MAX_COMMAND_CHARS),
        now,
    );
    populate_common_fields(&mut memory, observation, ExperienceScope::Repository);
    memory.success = Some(false);
    memory.failure_reason = Some(signal.summary.clone());
    memory.recommendation = Some("Edit the generator, schema, or source template instead".into());
    memory.what_failed = vec![signal.summary.clone()];
    memory.evidence = vec![signal.clone()];
    memory.refresh_confidence();
    memory
}

fn proves_architectural_boundary(signal: &EvidenceSignal) -> bool {
    let summary = signal.summary.to_ascii_lowercase();

    signal.is_verification()
        && contains_any(
            &summary,
            &[
                "architectural boundary verified",
                "architecture boundary verified",
                "service boundary verified",
                "integration boundary verified",
                "boundary contract verified",
            ],
        )
}

